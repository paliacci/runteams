# -*- coding: utf-8 -*-
"""失败三态 —— 从 driver.py 忠实提取,厂中立。

调度器(未来的 max_fail 安全阀)靠这三类区别对待失败:
- RateLimited / Transient = **外因**,不计失败次数、下轮重试(账号撞上限、网络抖动,不是活儿本身有问题)。
- 其它 RuntimeError = **确定性/结构性失败**,计入 max_fail;连续到上限就停到「阻塞」浮出来给人看。

driver.py 的教训(见其 1278-1302 行注释):确定性失败若无上限地重试,会霸占唯一 worker 槽、
饿死排队的卡 = 整条流水线"卡住"的真身。所以三态分类不是锦上添花,是可靠性的地基。
"""


class RateLimited(RuntimeError):
    """账号撞到用量/会话/周/月上限。瞬时外因,不计失败次数,释放认领下轮重试。
    调度器会优先解析明确刷新时间并持久等待到该时间点,避免逐卡空转。"""


class Transient(RuntimeError):
    """瞬时网络错误(连接中途断/reset)。不计失败次数、不全局暂停,仅释放下轮重试。"""


class Cancelled(RuntimeError):
    """用户主动停止运行。不是岗位失败，不累计失败次数。"""
