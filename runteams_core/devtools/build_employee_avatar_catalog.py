"""Generate the shared browser catalog from the owned avatar manifest."""
import argparse
import base64
import json
from runteams_core.foundation.resources import root


def expected():
    source = root()
    catalog = json.loads((source / 'web/worker-avatars/presets.json').read_text())
    # Exact byte comparison also replaces old robot SVGs embedded in frozen
    # employee pictures. Other data URLs, uploads and custom art pass through.
    pictures = { 'data:image/svg+xml;base64,' + base64.b64encode(
        (source / 'web/worker-avatars/bottts' / (item['id'] + '.svg')).read_bytes()).decode():
        'preset:colleague:' + item['target'] for item in catalog['legacy'] }
    pictures.update({ 'data:image/svg+xml;base64,' + base64.b64encode(
        (source / 'web/worker-avatars/colleague' / (item['id'] + '.svg')).read_bytes()).decode():
        'preset:colleague:' + item['id'] for item in catalog['presets'] })
    return '''/* Generated by runteams_core.devtools.build_employee_avatar_catalog. */
(function(root){
'use strict';
const catalog=CATALOG,pictures=new Map(Object.entries(PICTURES));
const presets=new Set(catalog.presets.map(item=>'preset:colleague:'+item.id));
const oldReferences=new Map(catalog.legacy.flatMap(item=>[
 ['preset:bottts:'+item.id,'preset:colleague:'+item.target],
 ['assets/avatars/'+item.sha256+'.svg','preset:colleague:'+item.target]
]));
const fallback='preset:colleague:'+catalog.default;
const artwork=new Map([...pictures].map(([data,preset])=>[preset,data])),livePictures=new Map();
function canonical(value,worker){
 const ref=String(value||'');
 if(presets.has(ref))return ref;
 if(ref.startsWith('preset:'))return oldReferences.get(ref)||'';
 // A custom attachment wins over a filename that happens to match an old hash.
 if(worker?.avatar_src)return pictures.get(worker.avatar_src)||'';
 return oldReferences.get(ref)||'';
}
function src(value,worker){
 const preset=canonical(value,worker);
 if(preset)return '/worker-avatars/colleague/'+preset.slice(17)+'.svg';
 if(typeof worker?.avatar_src==='string'&&/^data:image\\/(?:png|jpeg|webp|svg\\+xml);base64,[A-Za-z0-9+/=]+$/.test(worker.avatar_src))return worker.avatar_src;
 if(/^upload:[a-f0-9]{64}\\.webp$/.test(String(value||'')))return '/api/worker-avatar/upload/'+value.slice(7);
 return '/worker-avatars/colleague/'+catalog.default+'.svg';
}
function matches(item,value,worker){return item.avatar===canonical(value,worker)||item.avatar===value||item.asset_avatar===value;}
function liveMarkup(value,worker){
 const preset=canonical(value,worker),data=artwork.get(preset);
 if(!data)return '';
 if(!livePictures.has(preset)){
  // Only repository-owned preset bytes can become inline artwork. Attachments
  // remain images; scripts/animation are never added to portable employee files.
  const svg=atob(data.slice(data.indexOf(',')+1))
   .replace(/<title>[^<]*<\\/title>/g,'').replace(/ role="img"| aria-label="[^"]*"/g,'')
   .replace(/id="([^"]+)"/g,'id="rt-chat-avatar-$1"')
   .replace(/url\\(#([^)]*)\\)/g,'url(#rt-chat-avatar-$1)')
   .replace('<svg ','<svg class="employee-avatar-live" data-live-employee-avatar="'+preset.slice(17)+'" aria-hidden="true" focusable="false" ');
  livePictures.set(preset,svg);
 }
 return livePictures.get(preset);
}
const api=Object.freeze({src,canonical,matches,liveMarkup,defaultAvatar:fallback});
if(typeof module==='object'&&module.exports)module.exports=api;
else root.RunTeamsEmployeeAvatars=api;
})(typeof window==='undefined'?globalThis:window);
'''.replace('CATALOG', json.dumps(catalog, separators=(',', ':'))).replace('PICTURES', json.dumps(pictures, separators=(',', ':')))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = root() / 'web/ui/employee-avatars.js'
    body = expected()
    if args.check:
        if target.read_text() != body:
            parser.exit(2, 'Regenerate the employee avatar browser catalog.\n')
    else:
        target.write_text(body)
    catalog = json.loads((root() / 'web/worker-avatars/presets.json').read_text())
    print(json.dumps({'presets': len(catalog['presets']), 'featured': len(catalog['featured']), 'checked': args.check}))


if __name__ == '__main__':
    main()
