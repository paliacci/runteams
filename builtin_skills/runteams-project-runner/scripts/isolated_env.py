#!/usr/bin/env python3
"""Create an isolated scratch environment for running a project inside the workspace.

Writes .scratch/env.sh (HOME, TMPDIR, XDG_* and chosen data variables all point
inside .scratch/, plus free localhost ports) and records the environment in
.runteams/project-runner.json so cleanup-verify can later prove it was torn down.
"""

import argparse
import json
import os
from pathlib import Path
import re
import shlex
import socket
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _result import emit  # noqa: E402

TOOL = "isolated-env"
REGISTRY = Path(".runteams") / "project-runner.json"




def free_ports(count):
    sockets, ports = [], []
    try:
        for _ in range(count):
            handle = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            handle.bind(("127.0.0.1", 0))
            sockets.append(handle)
            ports.append(handle.getsockname()[1])
    finally:
        for handle in sockets:
            handle.close()
    return ports


def main(arguments=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--ports", type=int, default=2)
    parser.add_argument("--var", action="append", default=[],
                        help="extra environment variable to point at its own .scratch/data/<name> directory")
    parser.add_argument("--runtime", choices=["runteams"],
                        help="isolate every RunTeams persistent data directory")
    args = parser.parse_args(arguments)
    if not 0 <= args.ports <= 10:
        return emit(TOOL, False, "端口数量必须在 0 到 10 之间", code="invalid_arguments")
    for name in args.var:
        if not re.fullmatch(r"[A-Z_][A-Z0-9_]{0,63}", name):
            return emit(TOOL, False, "环境变量名无效：{}".format(name), code="invalid_arguments")
    root = Path(".scratch").resolve()
    directories = {"HOME": root / "home", "TMPDIR": root / "tmp",
                   "XDG_CACHE_HOME": root / "xdg" / "cache",
                   "XDG_CONFIG_HOME": root / "xdg" / "config",
                   "XDG_DATA_HOME": root / "xdg" / "data"}
    for name in args.var:
        directories[name] = root / "data" / name.lower()
    if args.runtime == "runteams":
        # A test instance must override every persistent root inherited from
        # the host, rather than only its primary SQLite directory.
        for name in ("RUNTEAMS_DATA", "RUNTEAMS_CORE_DATA", "RUNTEAMS_WORKSPACES"):
            directories[name] = root / "data" / name.lower()
    for path in directories.values():
        path.mkdir(parents=True, exist_ok=True)
    ports = free_ports(args.ports)
    lines = ["# Generated by project-runner/isolated-env. Load with: . .scratch/env.sh"]
    lines += ["export {}={}".format(name, shlex.quote(str(path))) for name, path in directories.items()]
    lines += ["export PYTHONDONTWRITEBYTECODE=1", "export CI=1"]
    if args.runtime:
        lines += ["export RUNTEAMS_SECRET_VAULT={}".format(shlex.quote(
            str(directories["RUNTEAMS_DATA"] / "secrets.json")))]
    lines += ["export RUNNER_PORT_{}={}".format(index + 1, port) for index, port in enumerate(ports)]
    (root / "env.sh").write_text("\n".join(lines) + "\n", encoding="utf-8")
    REGISTRY.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY.write_text(json.dumps({"scratch": str(root), "ports": ports,
                                    "variables": sorted(directories)}, ensure_ascii=False),
                        encoding="utf-8")
    summary = "已建立隔离环境：每条项目命令前执行 . .scratch/env.sh；可用端口 {}".format(
        ", ".join(str(port) for port in ports) or "无")
    return emit(TOOL, True, summary, output="\n".join(lines))


if __name__ == "__main__":
    raise SystemExit(main())
